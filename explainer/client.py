"""Nexus 를 부르는 것 — `BOUNDARY.md` §3.

**전송은 주입받는다.** 이 조각의 관심사가 아니고, 그래야 시험이 실물 스택 없이
물린다. 그리고 표면이 바뀌어도(HTTP → MCP) 고칠 자리가 하나로 남는다.
"""

#: ⛔ **이 층이 치는 유일한 표면이다. `/search` 로 바꾸지 않는다** (khala, 2026-09-22).
#:
#: ⛔ **아래 기제는 khala 가 오보로 정정했다 (2026-09-23, `#548`).** 여기 「저쪽 표면 셋이 같은
#: 요청 모델을 쓴다」고 적혀 있었는데 틀렸다 — `identifier_channel` 은 `AnswerRequest` 의 칸이고
#: `/search` 는 `SearchRequest` 를 받는다. **그 라우트에는 그 칸이 없다. 보내면 pydantic 이 모르는
#: 칸을 조용히 버린다.** 그러니 한 라우트의 한 깃발 문제가 아니라 요청 모델 전부가 그렇다 — 오타든
#: 낡은 깃발이든 200 · 처치 없음 · 신호 없음. **결론은 그대로다**: 켜서 보내면 200 이 오는데 처치는
#: 안 걸리고, 응답에 `identifier_channel` 도 `identifier_channel_asked` 도 안 실려서 **버려졌다는
#: 것을 알 방법이 없다.** khala 가 모르는 칸을 422 로 거절하는 변경(`#550`)을 올렸고 이 층은 반대하지
#: 않는다고 답했으며 같은 날 머지됐다(`cd6d72a`) — **지금부터 모르는 요청 칸은 422 다.** 이 함수는 아는 키만
#: 조립하고(`tests/test_explainer_client.py` 가 그 키들을 글자로 고정한다) 경계에서 실패하는 쪽이 조용한 열화보다
#: 이 층의 규율에 맞다. 실물 판에서 422 가 나면 이 층이 모르는 키를 보냈다는 신호다.
#:
#: ⛔ **그 표면으로 T2 를 재면 T0 를 재면서 T2 라고 적게 된다.** 「검색이 줬나」를 답변
#: 경로 대신 검색 경로에서 직접 재고 싶어지는 날이 이 덫이 놓인 자리다. 재게 되면
#: **먼저 저쪽에 말한다.**
ANSWER = "/search/answer"


#: 근거 예산. **답변 경로의 값은 20 이다** — 8 은 저쪽이 검색 전용 경로에 정한 값이다.
#:
#: ⛔ **8 을 보내고 있었다** (실측 2026-09-19). 불투명한 정지 코드 건에서 그 코드를
#: 설명하는 문서를 **찾아오긴 했는데 도입부 덩어리만** 왔다. 코드표가 든 덩어리는
#: 9~14위라 8 에서 잘렸고, 모델은 「제공된 근거에서 확인할 수 없습니다」라고 정확히
#: 답했다. **지어내지 않은 것은 옳고, 줄 것을 안 준 것이 내 쪽이다.**
#:
#:     k= 8   문서 덩어리 1개(도입부)  · 코드가 든 덩어리 없음
#:     k=20   문서 덩어리 3~4개        · 코드가 든 덩어리 9~14위
#:
#: 저쪽이 `AnswerRequest` 주석에 20 을 정한 근거도 같은 모양이다 — 10 에서 자르다
#: 놓친 것을 재서 올렸다. **근거 분량이 늘면 합성도 느려진다**(실측 필요).
ANSWER_TOP_K = 20


#: 사건 질의에서 뺄 문서 종류. **운영자 질의에는 안 보낸다** — 그때는 설계 문서도 답할
#: 값이 있다.
#:
#: ⛔ **설계 일지 한 편이 상위 20 중 다섯에서 일곱 자리를 매번 차지한다** (khala 실측
#: 2026-09-20). 이 층의 I 판 본문 인용 72건 중 21건(29%)이 그 문서였고, 답의 청중이
#: 운영자가 아니라 개발자가 됐다. 그 문서는 `spec` 이고, 골든셋 설계가 그 안에 있어
#: 지표 1 의 분모도 흔든다.
#:
#: 살아 있는 색인에서 `picasso` 테넌트를 세면 이 둘이 넷이다 — `spec` 셋(설계 일지 ·
#: 코어 설계 · 완료 기준)과 `design_doc` 하나(아키텍처). **합성 SOP 여섯은 `policy` 라
#: 남는다**(2026-09-20 실측).
#:
#: ⚠ **자리를 비울 뿐 맞는 문서를 올리지 않는다.** 사건의 실패 분류로 그 절차 문서가
#: 안 찾아지는 문제는 따로 열려 있다(`correspondence/` 의 khala 요청 ①). 저쪽도 자기
#: 구현 주석에 같은 구분을 적었다.
INCIDENT_EXCLUDED = ("spec", "design_doc")


def nexus_client(base_url, token, tenant, transport, top_k=ANSWER_TOP_K,
                 exclude_doc_types=(), identifier_channel=False):
    """`ask_once` 에 넘길 `search` 를 만든다. `(status, body)` 를 돌려준다.

    **테넌트를 부르는 쪽이 명시한다.** 서버가 토큰으로 범위를 정하고 범위 밖을
    부르면 조용히 좁혀지므로(2026-09-18 실측) 이것이 보안 장치는 아니다 —
    **아무 데나 묻지 않는다는 규율**이고, 넓히려면 선언을 고친다.
    """

    def search(query):
        return transport(
            "POST",
            base_url.rstrip("/") + ANSWER,
            {
                "Authorization": f"Bearer {token}",
                "Content-Type": "application/json; charset=utf-8",
            },
            # **안 물었으면 키를 안 보낸다.** 빈 목록도 저쪽에서는 「안 물었다」와 같은
            # SQL 이지만, 보내면 이 층이 물은 것으로 기록에 남는다.
            {"query": query, "tenant": tenant, "top_k": top_k,
             **({"exclude_doc_types": list(exclude_doc_types)} if exclude_doc_types else {}),
             # ⛔ **기본이 꺼짐이어야 측정이 선다** (khala 사전 등록 T2). 안 물었으면
             # 키를 안 보낸다 — 거짓을 보내면 이 층이 물은 것으로 저쪽 기록에 남는다.
             **({"identifier_channel": True} if identifier_channel else {})},
        )

    return search
