"""운영자 답변 카드 — 답 앞의 다섯 줄.

⛔ **답이 길고 청중이 개발자였다**(2026-09-20 실측). 아홉 답 중앙값 2,637자, 본문 인용 72건
중 21건이 picasso 설계 문서, 아홉 중 다섯이 「설계-관측 구분」 절을 가졌다. 운영자가 먼저 볼
것을 라벨 다섯 줄로 앞에 세운다 — 절차 · 우선 조치 · 금지 · 판별 기준 · 근거 강도.

**파싱은 결정적이다.** 라벨이 없으면 답변 카드가 없는 것이고 지어내지 않는다. 라벨마다 인용
하나를 요구하므로(`composer.CARD_NOTE`) 근거 없는 줄은 「근거 없음」이 된다.

라벨 다섯에 「무엇」과 「왜」가 없는 것은 의도다 — 무엇이 일어났는지는 화면에 이미 있고
(`composer.SCREEN_NOTE`), 왜의 후보 순위는 본문이 든다. 답변 카드는 **할 일**만 든다.

앞 [HEAD_LINES] 줄만 본다. 본문 한가운데의 「금지:」는 답변 카드가 아니다. 모델이 라벨 앞에
머리말을 길게 두면 답변 카드를 못 읽는데, 그것은 **덜 세는 쪽**으로 틀리는 것이다. 라벨 줄과 빈 줄이 12줄 밖으로
이어지면 창이 따라 늘어난다(`head_window`, 2026-10-04).
"""

import re

LABELS = ("절차", "먼저", "금지", "갈림", "근거 세기")

#: 한 줄. 글머리표와 굵게를 허용한다 — 모델이 마크다운으로 꾸며도 라벨은 라벨이다.
#: 굵게는 콜론 앞(`**먼저**:`)에서도 뒤(`**절차:**`)에서도 닫힐 수 있어 둘 다 받는다.
LINE = re.compile(
    r"^\s*(?:[-*]\s*)?(?:\*\*)?(절차|먼저|금지|갈림|근거 세기)(?:\*\*)?\s*[:：]\s*(?:\*\*)?\s*(\S.*?)\s*$"
)

#: 라벨을 찾을 앞부분. 본문 한가운데의 「금지:」는 답변 카드가 아니다.
HEAD_LINES = 12


#: 헤더 윈도우를 늘릴지 가르는 라벨 줄 — 권고 · 이유 · 다섯 라벨, **값이 비어도** 라벨 줄이다. 꾸밈은 진단 답의 헤더 줄과
#: 같게 받는다(글머리표 · 굵게, 줄머리 `#` 는 권고 · 이유에만 — 진단 답의 `_marker` 와 같은 줄을 받게, 2026-10-04 재검토). 값을 뽑는 것은 `LINE` 이 따로 한다 — 이것은 창의 경계만 정한다.
#: 세 읽개(답변 카드 · 진단 답 · 내보내기)가 이 하나를 써야 창이 같다(2026-10-04 검토 — 기준이 다르면 한쪽만 창이 늘어
#: 라벨이 답변 카드에도 본문에도 없이 사라졌다).
HEAD_MARKER = re.compile(r"^\s*(?:(?:#{1,6}\s*)?(?:[-*]\s*)?(?:\*\*)?(?:권고|이유)|(?:[-*]\s*)?(?:\*\*)?(?:절차|먼저|금지|갈림|근거 세기))(?:\*\*)?\s*[:：]")


def head_window(lines):
    """헤더 윈도우의 줄 번호 — 앞 [HEAD_LINES] 줄, 그리고 그 머리가 이어지는 데까지.

    ⛔ **끝까지 한 번의 답변 카드가 넷이었다 (2026-10-04).** 모델이 라벨 줄마다 빈 줄을 띄우면 다섯째 라벨이 13번째
    줄로 밀린다. 앞 12줄 안의 **첫 라벨 줄부터 12번째 줄까지가 라벨 줄과 빈 줄뿐이면**(`HEAD_MARKER`) 창은 그 뒤로
    라벨 줄과 빈 줄이 이어지는 데까지 늘어난다 — 진단 답의 본문이 머리를 정하는 규칙과 같다. 글이 있는 다른 줄이
    머리 사이에 끼었거나 앞 12줄에 라벨이 없으면 늘지 않는다. 창은 넓어지기만 한다 — 앞 12줄은 언제나 창 안이다.
    """
    n = min(len(lines), HEAD_LINES)
    window = list(range(n))
    first = next((i for i in range(n) if HEAD_MARKER.match(lines[i])), None)
    if first is not None and all(not lines[i].strip() or HEAD_MARKER.match(lines[i]) for i in range(first, n)):
        i = n
        while i < len(lines) and (not lines[i].strip() or HEAD_MARKER.match(lines[i])):
            window.append(i)
            i += 1
    return window


def parse_card(answer):
    """헤더 윈도우(`head_window`)의 라벨 줄을 `{표지: 문장}` 으로. **하나도 없으면 빈 사전.**"""
    card = {}
    lines = (answer or "").splitlines()
    for i in head_window(lines):
        match = LINE.match(lines[i])
        if match and match.group(1) not in card:
            card[match.group(1)] = match.group(2)
    return card
