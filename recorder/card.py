"""운영자 카드 — 답 앞의 다섯 줄.

⛔ **답이 길고 청중이 개발자였다**(2026-09-20 실측). 아홉 답 중앙값 2,637자, 본문 인용 72건
중 21건이 picasso 설계 일지, 아홉 중 다섯이 「설계-관측 구분」 절을 가졌다. 운영자가 먼저 볼
것을 표지 다섯 줄로 앞에 세운다 — 절차 · 먼저 · 금지 · 갈림 · 근거 세기.

**파싱은 결정적이다.** 표지가 없으면 카드가 없는 것이고 지어내지 않는다. 표지마다 인용
하나를 요구하므로(`composer.CARD_NOTE`) 근거 없는 줄은 「근거 없음」이 된다.

표지 다섯에 「무엇」과 「왜」가 없는 것은 의도다 — 무엇이 일어났는지는 화면에 이미 있고
(`composer.SCREEN_NOTE`), 왜의 후보 순위는 본문이 든다. 카드는 **할 일**만 든다.

앞 [HEAD_LINES] 줄만 본다. 본문 한가운데의 「금지:」는 카드가 아니다. 모델이 표지 앞에
머리말을 길게 두면 카드를 못 읽는데, 그것은 **덜 세는 쪽**으로 틀리는 것이다.
"""

import re

LABELS = ("절차", "먼저", "금지", "갈림", "근거 세기")

#: 한 줄. 글머리표와 굵게를 허용한다 — 모델이 마크다운으로 꾸며도 표지는 표지다.
#: 굵게는 콜론 앞(`**먼저**:`)에서도 뒤(`**절차:**`)에서도 닫힐 수 있어 둘 다 받는다.
LINE = re.compile(
    r"^\s*(?:[-*]\s*)?(?:\*\*)?(절차|먼저|금지|갈림|근거 세기)(?:\*\*)?\s*[:：]\s*(?:\*\*)?\s*(\S.*?)\s*$"
)

#: 표지를 찾을 앞부분. 본문 한가운데의 「금지:」는 카드가 아니다.
HEAD_LINES = 12


def parse_card(answer):
    """앞부분의 표지 줄을 `{표지: 문장}` 으로. **하나도 없으면 빈 사전.**"""
    card = {}
    for line in (answer or "").splitlines()[:HEAD_LINES]:
        match = LINE.match(line)
        if match and match.group(1) not in card:
            card[match.group(1)] = match.group(2)
    return card
